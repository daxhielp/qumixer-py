#!/usr/bin/env python3
"""Generate ``docs/tiers.md`` from the live registry, so it cannot drift.

    python tools/gen_tiers.py > docs/tiers.md

Everything in the generated page that *can* be derived from code is derived
from code: the parameter table comes from ``REGISTRY``, and the taper table
comes from the ``Taper`` objects in ``qumixer_py.protocol.units`` and from which
``ParamSpec``s actually reference them. Only the prose and the open-questions
list are hand-written, and those describe process, not facts about the code.

Never hand-edit ``docs/tiers.md``; re-run this instead.
``tests/test_docs.py::test_the_tier_table_matches_the_registry`` fails if you
forget.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from qumixer_py.protocol import units
from qumixer_py.protocol.params import Interpolated, ParamSpec
from qumixer_py.protocol.registry import REGISTRY
from qumixer_py.protocol.units import Taper

PREAMBLE = """\
# Parameter tiers

Generated by `tools/gen_tiers.py` from the live registry. Do not hand-edit
this file; re-run the script.

| Tier | Meaning |
|---|---|
| `VERIFIED` | Confirmed against physical hardware by the hardware calibration run. |
| `SUPPORTED` | Transcribed from the spec, round-tripped against a golden vector, exercised against `FakeQu` — but never seen by a real console. |
| `EXPERIMENTAL` | Something about the encoding, the addressing or the semantics is still an open question. |

**No parameter is at `VERIFIED` in this release.** The hardware hardware run has not
happened, and `VERIFIED` is set by the calibration tool
(`tools/calibrate.py`), never by hand. Treat the whole table as `SUPPORTED`
at best.
"""

TAPER_PREAMBLE = """\
## Tapers

`.raw` is always exact. `.db` is a convenience conversion through one of the
tapers below, and is approximate — about ±0.5 dB even for a verified curve,
which is simply the limit of 128 steps across the range.

`verified` here means "transcribed from anchor points the spec actually
measures, or from a relationship the spec states exactly" — **not** "checked
against hardware". An unverified taper is a best-effort interpolation between
two endpoints and may be wrong in the middle by a lot; frequency, filter
width, and the gate/compressor times are the ones to distrust.
"""

TAIL = """\
### The fader round-trip is deliberately asymmetric

`FADER_TAPER`'s lowest documented anchor is raw `0x0C` = −45 dB, but the
console does transmit raw `0x01`–`0x0B`. Those decode by extrapolating the
first segment (so `0x0B` and `0x00` stay distinguishable — `0x00` alone is
−∞), and they encode back to `0x00`.

So `raw -> db -> raw` does **not** round-trip in `0x01`–`0x0B`, on purpose:
inventing anchor points the spec does not give would be worse than an honest
asymmetry. `db -> raw -> db` is not exact anywhere, by design. Tests assert
tolerance, never equality.

`ParamProxy.is_approximate` is `True` for a reading that was extrapolated
past the documented anchors, and for any reading taken through an unverified
taper.

## Open questions

Each of these needs a physical console. Until one is answered, the behaviour
in the "interim" column is what ships. The hardware conformance suite
(`tests/hardware/test_conformance.py`, run with
`pytest -m hardware --qu-host=<ip>`) is written and skips cleanly without
hardware; it has not been run against a real console.

| Question | Interim behaviour | Test that would answer it |
|---|---|---|
| Does a Qu-24 have groups 5-6 and 7-8? | `CAPS_BY_BOX_ID[2].groups = 2`, `groups_provisional=True`, so an out-of-range group warns and is permitted rather than refused | `test_whether_a_qu24_has_group_5_6` |
| Which Qu-24 meter layout is right, `180 unused` or `100`? | `LAYOUTS["qu24"] = QU24_AS_WRITTEN`; the runtime frame-size check is authoritative over the table (protocol note 12) | `test_which_qu24_meter_layout_is_correct` |
| Does dSNAKE gain/pad/48V address anything in `CH`? | `Tier.EXPERIMENTAL`; cached on the socket in `VX` | `test_dsnake_addressing` |
| What `CH` does Group Mode (`5E`) report on? | Accepted from any `CH`, cached under the synthetic `GLOBAL` channel | `test_group_mode_reports_its_channel` |
| Does the console echo writes at all? | Assumed yes; a missing echo inside `echo_window` downgrades to `UNCONFIRMED` | `test_whether_the_console_echoes_writes` |
| How long may a channel name be? | `MAX_NAME_LENGTH = 6` | `test_measure_the_name_length_limit` |
| What happens at MIDI channel 16? | The strip sub-API is disabled outright (protocol note 11) | `test_behaviour_at_midi_channel_16` |
| How long does a scene recall actually take to settle? | `SCENE_SETTLE_DELAY = 0.5 s` (protocol note 13) | `test_measure_the_scene_recall_settling_time` |
| Does the console emit `55/07` or `18` for LR assign? | Write `18` only; normalise both on read (protocol note 8) | observe a live LR-assign toggle under `qumixer-py monitor` |
| Where do the unverified tapers actually bend? | Endpoint interpolation, `verified=False` | `tools/calibrate.py` |
"""


def _vx_label(spec: ParamSpec) -> str:
    name = type(spec.vx).__name__
    fixed = getattr(spec.vx, "value", None)
    if name == "Fixed" and isinstance(fixed, int):
        return f"Fixed `{fixed:#04x}`"
    return name


def _domain_label(spec: ParamSpec) -> str:
    return type(spec.domain).__name__


def _applies_to(spec: ParamSpec) -> str:
    return ", ".join(sorted(cls.name for cls in spec.applies_to))


def _cell(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ").strip()


def _taper_users() -> dict[int, list[str]]:
    users: dict[int, list[str]] = {}
    for spec in REGISTRY:
        if isinstance(spec.domain, Interpolated):
            users.setdefault(id(spec.domain.taper), []).append(spec.name)
    return users


def emit() -> str:
    out: list[str] = [PREAMBLE, "", "## Parameters", ""]
    out.append("| Parameter | ID | VX | Domain | Applies to | Direction | Tier | Notes |")
    out.append("|---|---|---|---|---|---|---|---|")
    rows = sorted(REGISTRY, key=lambda s: (s.tier.name, s.name, _applies_to(s)))
    for spec in rows:
        out.append(
            f"| `{spec.name}` | `{spec.nrpn_id:#04x}` | {_vx_label(spec)} | "
            f"{_domain_label(spec)} | {_cell(_applies_to(spec))} | "
            f"{spec.direction.name} | {spec.tier.name} | {_cell(spec.notes)} |"
        )
    out.append("")
    out.append(f"{len(rows)} registry rows, {len({s.name for s in rows})} distinct names.")
    out.append("")
    out.append(TAPER_PREAMBLE)
    out.append("")
    out.append("| Taper | verified | Anchors | Range | Used by |")
    out.append("|---|---|---|---|---|")
    users = _taper_users()
    tapers = sorted(
        ((name, obj) for name in dir(units) if isinstance(obj := getattr(units, name), Taper)),
        key=lambda pair: (not pair[1].verified, pair[0]),
    )
    for name, taper in tapers:
        lo, hi = taper.points[0][1], taper.points[-1][1]
        used = ", ".join(f"`{n}`" for n in sorted(set(users.get(id(taper), [])))) or "--"
        out.append(
            f"| `{name}` | {'yes' if taper.verified else '**no**'} | {len(taper.points)} | "
            f"{lo:g}..{hi:g} {taper.unit} | {used} |"
        )
    out.append("")
    out.append(TAIL)
    return "\n".join(out)


def main() -> None:
    sys.stdout.write(emit())


if __name__ == "__main__":
    main()
